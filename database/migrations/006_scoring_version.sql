-- 006 — 신호에 배점 체계 버전을 새긴다 (적중률 통계가 섞이지 않게)
--
-- 2026-09-04 08:52:30 KST 에 배점표 v3 이 적용됐다(엔진 재시작 시각). 그 전후의
-- 신호는 서로 다른 규칙으로 만들어진 다른 것이라, 섞어서 평균을 내면 "고쳤더니
-- 나아졌는가"를 영원히 알 수 없다.
--
-- **이 파일이 날짜를 쓰는 유일한 곳이다.** 앞으로는 신호를 만들 때 엔진이
-- `strategy/versioning.py` 의 값을 같이 저장하므로, 다음에 배점표를 고칠 때
-- 날짜를 다시 찾을 필요가 없다.
--
-- 기본값을 'v3' 으로 두는 이유: 이 마이그레이션 이후에 들어오는 행은 전부 v3 이다.
-- 기존 행만 아래 UPDATE 로 'v2' 로 되돌린다.
-- ---------------------------------------------------------------------------
ALTER TABLE `ai_signals`
    ADD COLUMN `scoring_version` VARCHAR(8) NOT NULL DEFAULT 'v3' AFTER `timeframe`;

-- 전환 시각 이전에 만들어진 신호를 v2 로 되돌린다.
-- 경계에 걸친 신호는 없다(마지막 v2 신호 08:19:43, 재시작 08:52:30).
UPDATE `ai_signals`
   SET `scoring_version` = 'v2'
 WHERE `created_at` < '2026-09-04 08:52:30';

-- 적중률은 항상 버전별로 나눠 본다. 그 집계가 이 인덱스를 탄다.
ALTER TABLE `ai_signals`
    ADD INDEX `idx_scoring_version_created` (`scoring_version`, `created_at`);
